// Shopping list generation, quantity shortage calculations and manual items.
// --- SHOPPING LIST LOGIC ---
        function syncShoppingListFromPlan() {
            const allPlannedIds = Object.values(mealPlan).flat();
            const plannedRecipes = allPlannedIds
                .map(id => recipesDB.find(recipe => recipe.id === id))
                .filter(Boolean);
            const demandMap = new Map();
            const unparsedDemands = new Map();

            // Add up the quantities required by every planned recipe before checking stock.
            plannedRecipes.forEach(recipe => {
                recipe.ingredients.forEach(ingredient => {
                    const nameOptions = getIngredientNameOptions(ingredient.name);
                    const canonicalNames = nameOptions.map(canonicalIngredientName).sort();
                    const requirement = parseQuantity(ingredient.qty);

                    if (!requirement) {
                        const key = `${canonicalNames.join('|')}::unparsed`;
                        const current = unparsedDemands.get(key) || { name: ingredient.name, qty: ingredient.qty, names: nameOptions };
                        unparsedDemands.set(key, current);
                        return;
                    }

                    const key = `${canonicalNames.join('|')}::${requirement.unitKey}`;
                    const current = demandMap.get(key) || {
                        name: ingredient.name,
                        names: nameOptions,
                        requirement,
                        requiredBaseValue: 0
                    };
                    current.requiredBaseValue += requirement.baseValue;
                    demandMap.set(key, current);
                });
            });

            const autoItems = [];
            demandMap.forEach((demand, key) => {
                const matchingItems = getMatchingInventoryEntries(demand.names.join(' or '));
                const parsedStock = matchingItems.map(item => parseQuantity(item.qty));
                let comparable = true;
                let stockBaseValue = 0;

                if (parsedStock.some(quantity => !quantity || quantity.unitKey !== demand.requirement.unitKey)) {
                    comparable = false;
                } else {
                    stockBaseValue = parsedStock.reduce((total, quantity) => total + quantity.baseValue, 0);
                }

                const missingBaseValue = comparable
                    ? Math.max(0, demand.requiredBaseValue - stockBaseValue)
                    : demand.requiredBaseValue;
                if (comparable && missingBaseValue <= 0.000001) return;

                const id = `auto_${key}`;
                const quantityText = formatQuantity(missingBaseValue, demand.requirement);
                const qtyLabel = comparable
                    ? quantityText
                    : `${quantityText} · check existing stock`;
                const existing = shoppingList.find(item => item.id === id)
                    || shoppingList.find(item => item.autoGenerated && canonicalIngredientName(item.name) === canonicalIngredientName(demand.name));

                autoItems.push({
                    id,
                    name: demand.name,
                    qty: qtyLabel,
                    checked: existing ? Boolean(existing.checked) : false,
                    autoGenerated: true
                });
            });

            unparsedDemands.forEach((demand, key) => {
                if (getMatchingInventoryEntries(demand.names.join(' or ')).length > 0) return;
                const id = `auto_${key}`;
                const existing = shoppingList.find(item => item.id === id);
                autoItems.push({
                    id,
                    name: demand.name,
                    qty: demand.qty,
                    checked: existing ? Boolean(existing.checked) : false,
                    autoGenerated: true
                });
            });

            const customItems = shoppingList.filter(item => !item.autoGenerated);
            shoppingList = [...autoItems, ...customItems];
            localStorage.setItem('pantry_shopping', JSON.stringify(shoppingList));
            renderShoppingList();
        }

        function renderShoppingList() {
            const listUl = document.getElementById('shopping-list-ul');
            const emptyState = document.getElementById('shopping-empty');
            const badge = document.getElementById('shopping-badge');

            listUl.innerHTML = '';

            if (shoppingList.length === 0) {
                emptyState.classList.remove('hidden');
                badge.classList.add('hidden');
            } else {
                emptyState.classList.add('hidden');
                badge.classList.remove('hidden');
                badge.innerText = shoppingList.filter(item => !item.checked).length;
            }

            shoppingList.forEach((item, idx) => {
                const li = document.createElement('li');
                li.className = "py-3 flex items-center justify-between gap-3";
                li.innerHTML = `
                    <div class="flex items-center gap-3 min-w-0">
                        <input type="checkbox" ${item.checked ? 'checked' : ''} onchange="toggleShoppingItem(${idx})" class="w-5 h-5 rounded border-slate-300 text-brand-600 focus:ring-brand-500 cursor-pointer shrink-0">
                        <div class="min-w-0">
                            <span class="text-sm ${item.checked ? 'line-through text-slate-400' : 'text-slate-700 dark:text-slate-200 font-medium'}">${escapeHTML(item.name)}</span>
                            ${item.qty ? `<p class="text-xs text-slate-500 dark:text-slate-400 mt-0.5">${escapeHTML(item.qty)}</p>` : ''}
                            ${item.autoGenerated ? '<span class="text-[10px] bg-slate-100 dark:bg-slate-700 text-slate-500 px-2 py-0.5 rounded-full inline-block mt-1">Auto-Added</span>' : ''}
                        </div>
                    </div>
                    <button onclick="removeShoppingItem(${idx})" class="text-slate-400 hover:text-rose-500 p-1 shrink-0" aria-label="Remove shopping list item">
                        <i data-lucide="x" class="w-4 h-4"></i>
                    </button>
                `;
                listUl.appendChild(li);
            });

            lucide.createIcons();
        }

        function addCustomShoppingItem(e) {
            e.preventDefault();
            const input = document.getElementById('custom-shopping-input');
            const val = input.value.trim();
            if (!val) return;

            shoppingList.push({
                id: 'shop_' + Date.now(),
                name: val,
                checked: false,
                autoGenerated: false
            });

            localStorage.setItem('pantry_shopping', JSON.stringify(shoppingList));
            input.value = '';
            renderShoppingList();
            showToast('Item added to shopping list!');
        }

        function toggleShoppingItem(idx) {
            shoppingList[idx].checked = !shoppingList[idx].checked;
            localStorage.setItem('pantry_shopping', JSON.stringify(shoppingList));
            renderShoppingList();
        }

        function removeShoppingItem(idx) {
            shoppingList.splice(idx, 1);
            localStorage.setItem('pantry_shopping', JSON.stringify(shoppingList));
            renderShoppingList();
        }

        function clearCheckedShopping() {
            shoppingList = shoppingList.filter(s => !s.checked);
            localStorage.setItem('pantry_shopping', JSON.stringify(shoppingList));
            renderShoppingList();
            showToast('Completed items cleared!');
        }

        function clearAllShopping() {
            shoppingList = [];
            localStorage.setItem('pantry_shopping', JSON.stringify(shoppingList));
            renderShoppingList();
            showToast('Shopping list cleared!');
        }

